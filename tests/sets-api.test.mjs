import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, symlink, rm, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { setsApi } from '../scripts/sets-api.mjs';

test('local API scans, branches and rejects cross-origin writes and invalid names', async (t) => {
  const root = await mkdtemp(path.join(tmpdir(), 'seraph-branches-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const library = path.join(root, 'Ableton');
  await mkdir(library);
  await symlink(fileURLToPath(new URL('../scripts', import.meta.url)), path.join(root, 'scripts'));
  const source = '<Ableton><LiveSet><Tracks/></LiveSet></Ableton>';
  await writeFile(path.join(library, 'original.als'), source);
  const template = path.join(root, 'blank.als');
  await writeFile(template, source);
  const opened = [];
  const middleware = setsApi(root, { library, template, openSet: async (file) => opened.push(file) });
  const server = createServer((req, res) => middleware(req, res, () => { res.writeHead(404); res.end(); }));
  t.after(() => new Promise((resolve) => { server.closeAllConnections(); server.close(resolve); }));
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const origin = `http://127.0.0.1:${server.address().port}`;
  const post = (route, body, requestOrigin = origin) => fetch(origin + route, {
    method: 'POST', headers: { Origin: requestOrigin, 'Content-Type': 'application/json' }, body: JSON.stringify(body),
  });
  assert.equal((await post('/api/sets/scan', {}, 'https://unrelated.example')).status, 403);
  const scan = await post('/api/sets/scan', {});
  assert.equal(scan.status, 200);
  const parent = (await scan.json()).sets[0];
  const created = await post('/api/sets/branch', { parent_id: parent.id, name: 'Quieter ending' });
  assert.equal(created.status, 201);
  const child = await created.json();
  assert.equal(child.parent_set_id, parent.id);
  assert.equal(await readFile(path.join(library, 'Quieter ending.als'), 'utf8'), source);
  const list = await (await fetch(origin + '/api/sets')).json();
  assert.equal(list.sets.length, 2);
  assert.equal((await post('/api/sets/branch', { parent_id: parent.id, name: '../escape' })).status, 400);
  assert.equal((await post('/api/sets/branch', { parent_id: parent.id, name: 'Quieter ending' })).status, 400);
  assert.equal((await post('/api/sets/branch', null)).status, 400);
  assert.equal((await post('/api/sets/open', { set_id: child.id })).status, 200);
  assert.deepEqual(opened, [await realpath(path.join(library, 'Quieter ending.als'))]);
  assert.equal((await post('/api/sets/open', { set_id: 'unknown' })).status, 404);
  assert.equal((await post('/api/sets/new', { name: '../escape' })).status, 400);
  const ideaResponse = await post('/api/sets/new', {});
  assert.equal(ideaResponse.status, 201);
  const idea = await ideaResponse.json();
  assert.ok(idea.project_id);
  await mkdir(path.join(root, 'apps/internal/data/songs'), { recursive: true });
  await writeFile(path.join(root, 'apps/internal/data/songs/song.md'), '---\nid: song\ntitle: A song\n---\n');
  assert.equal((await post('/api/sets/associate', { set_id: idea.id, song: 'missing' })).status, 400);
  assert.equal((await post('/api/sets/associate', { set_id: idea.id, song: 'song' })).status, 200);
  const work = await (await fetch(origin + '/api/sets/workspace')).json();
  assert.equal(work.sets.find((s) => s.id === idea.id).song, 'song');
  assert.equal(work.songs[0].latest_set_id, idea.id);
  const projectText = await readFile(path.join(root, 'apps/internal/data/projects', `${idea.project_id}.md`), 'utf8');
  assert.match(projectText, /"song": null/);
  const linked = work.sets.find((s) => s.id === idea.id);
  assert.match(linked.name, /^idea-\d{8}-[a-f0-9]{12}$/);
  const ideaText = await readFile(path.join(root, 'apps/internal/data/ideas', `${linked.idea_id}.md`), 'utf8');
  assert.match(ideaText, /song: song/);
  assert.equal(work.ideas.find((row) => row.id === linked.idea_id).song, 'song');
  assert.equal((await post('/api/sets/associate', { set_id: idea.id, song: null })).status, 200);
  const unlinked = await (await fetch(origin + '/api/sets/workspace')).json();
  assert.equal(unlinked.sets.find((s) => s.id === idea.id).idea_id, linked.idea_id);
  assert.equal(unlinked.sets.find((s) => s.id === idea.id).song, null);
  assert.match(projectText, /"created_at":/);
  assert.equal((await post('/api/sets/new', { name: 'Cross origin' }, 'https://example.com')).status, 403);
  const archived = await post('/api/sets/archive', { set_id: child.id });
  assert.equal(archived.status, 200);
  assert.ok((await archived.json()).archived_at);
  assert.equal((await post('/api/sets/open', { set_id: child.id })).status, 400);
  assert.equal((await post('/api/sets/branch', { parent_id: child.id, name: 'Blocked' })).status, 400);
  const restored = await post('/api/sets/restore', { set_id: child.id });
  assert.equal(restored.status, 200);
  assert.equal((await restored.json()).archived_at, undefined);
  assert.equal(await readFile(path.join(library, 'original.als'), 'utf8'), source);
  const outside = path.join(root, 'outside.als');
  await writeFile(outside, source);
  await symlink(outside, path.join(library, 'escape.als'));
  assert.equal((await post('/api/sets/scan', {})).status, 200);
  const escaped = (await (await fetch(origin + '/api/sets')).json()).sets.find((s) => s.paths.at(-1).endsWith('/outside.als'));
  assert.equal((await post('/api/sets/open', { set_id: escaped.id })).status, 400);
});
